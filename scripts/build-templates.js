#!/usr/bin/env node
// Precompiles EJS views into a self-contained CommonJS module for Cloudflare Workers.
// Run before packaging; the worker never executes EJS at runtime.
const fs = require('fs');
const path = require('path');
const ejs = require('ejs');

const ROOT = path.join(__dirname, '..');
const VIEWS_DIR = path.join(ROOT, 'views');
const OUT_FILE = path.join(ROOT, 'cloudflare', 'functions', '_templates.js');

const TEMPLATES = {
  layout: 'layout.ejs',
  home: 'home.ejs',
  list: 'list.ejs',
  tool: 'tool.ejs',
  partner: 'partner.ejs',
  info: 'info.ejs',
  admin: 'admin.ejs',
  'admin/traffic': path.join('admin', 'traffic.ejs'),
  'admin/posts': path.join('admin', 'posts.ejs'),
  'admin/tools': path.join('admin', 'tools.ejs'),
  'admin/submissions': path.join('admin', 'submissions.ejs'),
  'admin/keys': path.join('admin', 'keys.ejs'),
  'partials/card': path.join('partials', 'card.ejs'),
  'partials/ad': path.join('partials', 'ad.ejs'),
};

const LOCALS = {
  layout: [
    'pageTitle', 'siteName', 'pageDescription', 'siteTagline', 'canonical',
    'jsonLd', 'siteUrl', 'categories', 'currentPath', 'q', 'body', 'year', 'tags',
    'adsenseClient', 'googleAnalyticsId',
  ],
  home: [
    'siteTagline', 'siteName', 'siteUrl', 'newsPosts', 'featuredTools', 'toolPosts',
    'hotTools', 'categories', 'tags', 'currentPath', 'q', 'totalCount',
  ],
  list: [
    'currentPath', 'title', 'subtitle', 'q', 'items', 'categories', 'tags',
    'emptyText', 'siteName', 'siteUrl',
  ],
  tool: ['post', 'toc', 'related', 'latest', 'prev', 'next', 'canonical', 'siteName', 'siteUrl'],
  partner: ['siteName', 'siteUrl', 'contactEmail'],
  info: ['title', 'lead', 'eyebrow', 'content', 'siteName', 'siteUrl'],
  admin: [
    'page', 'siteName', 'siteUrl', 'needsSetup', 'adminError', 'adminNotice',
    'stats', 'traffic', 'apiKeys', 'csrf', 'newKey', 'workerLog', 'newsPosts',
    'scheduledPosts', 'toolPosts', 'partnerSubmissions', 'submissionStats',
    'trafficRange', 'sectionTitle', 'sectionLead',
  ],
  'admin/traffic': ['traffic', 'trafficRange', 'csrf'],
  'admin/posts': ['newsPosts', 'scheduledPosts', 'csrf'],
  'admin/tools': ['toolPosts'],
  'admin/submissions': ['partnerSubmissions', 'submissionStats', 'csrf'],
  'admin/keys': ['apiKeys', 'newKey', 'csrf', 'workerLog'],
  'partials/card': ['post', 'siteName'],
  'partials/ad': ['adsenseClient', 'adsenseSlots', 'slot'],
};

function compile(name, relPath) {
  const file = path.join(VIEWS_DIR, relPath);
  const source = fs.readFileSync(file, 'utf8');
  const fn = ejs.compile(source, {
    client: true,
    _with: false,
    localsName: 'locals',
    destructuredLocals: LOCALS[name] || [],
    filename: file,
  });
  return `  ${JSON.stringify(name)}: ${fn.toString()},`;
}

const lines = [
  '// GENERATED by scripts/build-templates.js - do not edit manually.',
  'module.exports = {',
  ...Object.keys(TEMPLATES).map((name) => compile(name, TEMPLATES[name])),
  '};',
  '',
];

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
console.log('templates written to', path.relative(ROOT, OUT_FILE));
